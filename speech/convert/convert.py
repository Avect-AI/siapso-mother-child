#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Converts the open Whisper models of SIAPSO into voice packs for Transformers.js.

Run from the repository root with `pnpm voice:convert` (or
`sh tools/hygiene/py.sh speech/convert/convert.py [--pack <id>]`). For each
pack the script:

1. checks the Python version (3.10 to 3.12), creates the virtual environment
   speech/convert/.venv and installs the pinned and hashed requirements
   (speech/convert/requirements.txt, generated by lock.py from
   requirements.in), then runs itself again inside it;
2. downloads the source model at its pinned revision;
3. exports it to ONNX with past key values (encoder and merged decoder) with
   optimum;
4. quantises both graphs to 8 bits (dynamic quantisation of MatMul, plus
   Gather for the token embedding, int8 weights), the `q8` data type of
   Transformers.js;
5. writes the pack, in the Transformers.js layout, with voice-pack.json
   (files with bytes and sha256, total size, licence, languages, decoder
   prompt, source revision) to speech/convert/out/<id>/.

Packs (speech/convert/README.md and docs/voice.md):
  whisper-small-wolof-q8  M9and2M/whisper-small-wolof, Wolof
  whisper-base-fr-q8      openai/whisper-base, French (the Wolof fine-tune
                          lost too much French: see docs/voice.md)

Nothing here is committed: speech/convert/out/ and the venv are git-ignored.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
VENV = HERE / ".venv"
REQUIREMENTS = HERE / "requirements.txt"
OUT = HERE / "out"
MIN_PYTHON = (3, 10)
MAX_PYTHON = (3, 12)

# OpenAI states that the Whisper code and model weights are released under
# the MIT License (README of github.com/openai/whisper, section "License");
# the Hugging Face repositories openai/whisper-small and openai/whisper-base
# declare apache-2.0 in their card metadata. Both licences are permissive.
WHISPER_LICENCE_NOTE = (
    "OpenAI releases the Whisper code and model weights under the MIT License "
    "(github.com/openai/whisper, README, section License); the Hugging Face card "
    "of the openai repository declares apache-2.0."
)

PACKS = {
    "whisper-small-wolof-q8": {
        "repo": "M9and2M/whisper-small-wolof",
        # Commit of 2024-07-26 ("Update README.md"), the head of main on 2026-11-03.
        "revision": "8cc20b3c6e77ecb490210103d3b4fd0b85c3d1d8",
        "licence": "MIT",
        "base": "openai/whisper-small",
        # Head of main of openai/whisper-small on 2026-11-04.
        "baseRevision": "973afd24965f72e36ca33b3055d56a652f456b4d",
        "baseLicence": "MIT",
        "language": "wo",
        # The fine-tune was trained with <|startoftranscript|> alone: it writes
        # the Wolof text right after it (checked with quick_check.py).
        "prompt": "sot",
    },
    "whisper-base-fr-q8": {
        "repo": "openai/whisper-base",
        # Head of main on 2026-11-04 (last change 2024-02-29).
        "revision": "e37978b90ca9030d5170a5c07aadb050351a65bb",
        "licence": "MIT",
        "base": None,
        "baseRevision": None,
        "baseLicence": None,
        "language": "fr",
        # The standard multilingual prompt: <|startoftranscript|><|fr|><|transcribe|><|notimestamps|>.
        "prompt": "fr",
    },
}

SOURCE_FILES = [
    "config.json",
    "generation_config.json",
    "preprocessor_config.json",
    "tokenizer_config.json",
    "special_tokens_map.json",
    "added_tokens.json",
    "vocab.json",
    "merges.txt",
    "normalizer.json",
    "model.safetensors",
]
# Files copied verbatim from the source model into the pack.
COPIED = ["config.json", "generation_config.json", "preprocessor_config.json"]
# Graphs loaded by Transformers.js for Whisper: onnx/<name>_quantized.onnx with dtype q8.
GRAPHS = ["encoder_model", "decoder_model_merged"]


def venv_python() -> Path:
    scripts = "Scripts" if os.name == "nt" else "bin"
    return VENV / scripts / ("python.exe" if os.name == "nt" else "python")


def in_venv() -> bool:
    return Path(sys.prefix).resolve() == VENV.resolve()


def check_python(version: tuple[int, int] = (sys.version_info[0], sys.version_info[1])) -> None:
    """The pinned set has wheels for Python 3.10 to 3.12 only (onnxruntime 1.23.2 among others)."""
    if not (MIN_PYTHON <= version <= MAX_PYTHON):
        raise SystemExit(
            f"Python {version[0]}.{version[1]} is not supported: the pinned requirements need "
            f"Python {MIN_PYTHON[0]}.{MIN_PYTHON[1]} to {MAX_PYTHON[0]}.{MAX_PYTHON[1]}. "
            "Run with one of these (on Windows: py -3.12 speech/convert/convert.py)."
        )


def bootstrap() -> None:
    """Creates the venv, installs the pinned requirements and runs this script inside it."""
    check_python()
    if not venv_python().exists():
        print(f"Creating the virtual environment {VENV}")
        subprocess.run([sys.executable, "-m", "venv", str(VENV)], check=True)
    print(f"Installing {REQUIREMENTS.name} into the virtual environment")
    # Every package pinned and hashed, wheels only: a missing pin or a changed
    # file fails the installation.
    subprocess.run(
        [
            str(venv_python()),
            "-m",
            "pip",
            "install",
            "--disable-pip-version-check",
            "--require-hashes",
            "--only-binary=:all:",
            "-r",
            str(REQUIREMENTS),
        ],
        check=True,
    )
    result = subprocess.run([str(venv_python()), str(Path(__file__).resolve()), *sys.argv[1:]])
    sys.exit(result.returncode)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def download(spec: dict, work: Path) -> Path:
    from huggingface_hub import snapshot_download

    source = work / "source"
    print(f"Downloading {spec['repo']} at {spec['revision']}")
    snapshot_download(
        repo_id=spec["repo"],
        revision=spec["revision"],
        allow_patterns=SOURCE_FILES,
        local_dir=str(source),
    )
    missing = [name for name in SOURCE_FILES if not (source / name).exists()]
    if missing:
        raise SystemExit(f"Missing files in the download: {', '.join(missing)}")
    return source


def export(source: Path, work: Path) -> Path:
    from optimum.exporters.onnx import main_export

    exported = work / "export"
    if exported.exists():
        shutil.rmtree(exported)
    print("Exporting to ONNX with past key values (encoder, merged decoder)")
    main_export(
        model_name_or_path=str(source),
        output=str(exported),
        task="automatic-speech-recognition-with-past",
        device="cpu",
        library_name="transformers",
    )
    for name in GRAPHS:
        if not (exported / f"{name}.onnx").exists():
            raise SystemExit(f"The export did not write {name}.onnx")
    return exported


def quantise(exported: Path, pack: Path) -> None:
    from onnxruntime.quantization import QuantType, quantize_dynamic

    onnx_dir = pack / "onnx"
    onnx_dir.mkdir(parents=True, exist_ok=True)
    for name in GRAPHS:
        target = onnx_dir / f"{name}_quantized.onnx"
        print(f"Quantising {name} to int8 (dynamic, MatMul and Gather)")
        # Same options as the q8 mode of the Transformers.js conversion script
        # (per channel, reduced range, subgraphs of the merged decoder included),
        # restricted to MatMul, plus Gather for the token embedding (159 MB in
        # 32-bit floats for Whisper small, 40 MB in int8), so every large weight
        # is int8.
        quantize_dynamic(
            model_input=str(exported / f"{name}.onnx"),
            model_output=str(target),
            op_types_to_quantize=["MatMul", "Gather"],
            per_channel=True,
            reduce_range=True,
            weight_type=QuantType.QInt8,
            extra_options={"EnableSubgraph": True, "MatMulConstBOnly": True},
        )


def tokenizer(source: Path, pack: Path) -> None:
    from transformers import WhisperTokenizerFast

    print("Writing tokenizer.json and tokenizer_config.json")
    fast = WhisperTokenizerFast.from_pretrained(str(source))
    staging = pack / ".tokenizer"
    fast.save_pretrained(str(staging))
    for name in ["tokenizer.json", "tokenizer_config.json"]:
        shutil.copyfile(staging / name, pack / name)
    shutil.rmtree(staging)


def decoder_prompt(source: Path, prompt: str) -> list[int]:
    """Token ids of the decoder prompt: `sot` alone, or the standard prompt of a language."""
    generation = json.loads((source / "generation_config.json").read_text(encoding="utf-8"))
    sot = generation["decoder_start_token_id"]
    if prompt == "sot":
        return [sot]
    return [
        sot,
        generation["lang_to_id"][f"<|{prompt}|>"],
        generation["task_to_id"]["transcribe"],
        generation["no_timestamps_token_id"],
    ]


def versions() -> dict[str, str]:
    from importlib.metadata import version

    names = ["torch", "transformers", "optimum", "optimum-onnx", "onnx", "onnxruntime"]
    return {name: version(name) for name in names}


def write_manifest(pack_id: str, spec: dict, pack: Path, prompt: list[int]) -> dict:
    files = []
    for path in sorted(p for p in pack.rglob("*") if p.is_file() and p.name != "voice-pack.json"):
        relative = path.relative_to(pack).as_posix()
        files.append({"path": relative, "bytes": path.stat().st_size, "sha256": sha256(path)})
    source = {"repo": spec["repo"], "revision": spec["revision"], "licence": spec["licence"]}
    if spec["base"] is not None:
        source.update(base=spec["base"], baseRevision=spec["baseRevision"], baseLicence=spec["baseLicence"])
    manifest = {
        "id": pack_id,
        "licence": spec["licence"],
        "licenceNote": WHISPER_LICENCE_NOTE,
        "languages": [spec["language"]],
        "prompts": {spec["language"]: prompt},
        "dtype": "q8",
        "source": source,
        "tools": versions(),
        "files": files,
        "totalBytes": sum(f["bytes"] for f in files),
    }
    (pack / "voice-pack.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


def convert(pack_id: str, out: Path, keep_work: bool) -> None:
    spec = PACKS[pack_id]
    work = out / "work" / pack_id
    pack = out / pack_id
    work.mkdir(parents=True, exist_ok=True)
    if pack.exists():
        shutil.rmtree(pack)
    pack.mkdir(parents=True)

    source = download(spec, work)
    exported = export(source, work)
    quantise(exported, pack)
    for name in COPIED:
        shutil.copyfile(source / name, pack / name)
    tokenizer(source, pack)
    manifest = write_manifest(pack_id, spec, pack, decoder_prompt(source, spec["prompt"]))
    if not keep_work:
        shutil.rmtree(exported)

    print(f"Voice pack written to {pack}")
    for entry in manifest["files"]:
        print(f"  {entry['bytes']:>12}  {entry['path']}")
    print(f"Total: {manifest['totalBytes']} bytes ({manifest['totalBytes'] / 1_000_000:.1f} MB)")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--pack", action="append", choices=sorted(PACKS), help="pack to build (default: all)")
    parser.add_argument("--out", type=Path, default=OUT, help="output folder (default: speech/convert/out)")
    parser.add_argument("--keep-work", action="store_true", help="keep the fp32 export in <out>/work/<id>")
    args = parser.parse_args()

    if not in_venv():
        bootstrap()

    for pack_id in args.pack or list(PACKS):
        convert(pack_id, args.out, args.keep_work)


if __name__ == "__main__":
    main()
