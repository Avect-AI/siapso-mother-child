// Command line: `siapso-server` starts the API, `siapso-server openapi`
// rewrites openapi.yaml from the request schema.
//
// Environment:
//   SIAPSO_API_KEYS_FILE   path of the JSON file of SHA-256 key hashes (required)
//   SIAPSO_PACK_FILE       path of pack.json (default app/public/pack/pack.json)
//   SIAPSO_QUOTA_PER_MINUTE  requests per key and minute (default 60)
//   PORT                   TCP port (default 8080)
//   HOST                   bind address (default 0.0.0.0)
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parsePack } from '@siapso/engine';
import { stringify } from 'yaml';
import { createAuthenticator, loadKeys } from './auth.js';
import { buildOpenApi } from './openapi.js';
import { createQuota } from './quota.js';
import { createServer } from './server.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SERVER_ROOT = path.resolve(HERE, '..');

// Split so that the REUSE tool does not read this line as a licence header of main.ts.
export const OPENAPI_HEADER = [
  ['# SPDX', 'License', 'Identifier: MIT'].join('-'),
  '# Generated by `pnpm --filter @siapso/server openapi` from src/validate.ts. Do not edit by hand.',
  '',
].join('\n');

function positiveInteger(name: string, value: string | undefined, fallback: number): number {
  if (value === undefined || value === '') return fallback;
  const number = Number(value);
  if (!Number.isInteger(number) || number < 1)
    throw new Error(`${name} must be a positive integer`);
  return number;
}

export async function main(args: string[]): Promise<number> {
  if (args[0] === 'openapi') {
    await writeFile(
      path.join(SERVER_ROOT, 'openapi.yaml'),
      OPENAPI_HEADER + stringify(buildOpenApi(), { lineWidth: 100 }),
    );
    return 0;
  }
  if (args.length > 0) {
    process.stderr.write('Usage: siapso-server [openapi]\n');
    return 2;
  }
  const env = process.env;
  const keysFile = env.SIAPSO_API_KEYS_FILE;
  if (keysFile === undefined || keysFile === '') {
    process.stderr.write('SIAPSO_API_KEYS_FILE is required (JSON file of SHA-256 key hashes)\n');
    return 2;
  }
  let entries;
  try {
    entries = await loadKeys(keysFile);
  } catch (error) {
    // The message of a bad key file never quotes the file; a read error is summarised.
    const known = error instanceof Error && error.message.startsWith('Invalid key file');
    process.stderr.write(
      `Cannot start: ${known ? error.message : 'the key file cannot be read'}\n`,
    );
    return 1;
  }
  if (entries.length === 0) {
    process.stderr.write('Cannot start: no API key in the key file (nobody could call the API)\n');
    return 1;
  }
  const packFile =
    env.SIAPSO_PACK_FILE ?? path.resolve(SERVER_ROOT, '..', 'app', 'public', 'pack', 'pack.json');
  const pack = parsePack(JSON.parse(await readFile(packFile, 'utf8')));
  const server = createServer({
    pack,
    authenticate: createAuthenticator(entries),
    quota: createQuota({
      limit: positiveInteger('SIAPSO_QUOTA_PER_MINUTE', env.SIAPSO_QUOTA_PER_MINUTE, 60),
      windowMs: 60_000,
    }),
    log: (line) => process.stdout.write(`${line}\n`),
  });
  const port = positiveInteger('PORT', env.PORT, 8080);
  await new Promise<void>((resolve) => server.listen(port, env.HOST ?? '0.0.0.0', resolve));
  process.stdout.write(
    `${JSON.stringify({ event: 'listening', port, packVersion: pack.version, keys: entries.length })}\n`,
  );
  const stop = (): void => {
    server.close(() => process.exit(0));
    server.closeIdleConnections();
  };
  process.on('SIGTERM', stop);
  process.on('SIGINT', stop);
  return await new Promise<number>(() => undefined);
}
